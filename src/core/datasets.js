/* ------------------------- 备用数据集 2：电商订单 ------------------------- */

function orderFrame() {
  const r = rng(20261009);
  const cities = ['北京', '上海', '广州', '深圳', '杭州', '成都'];
  const cats = ['数码', '家居', '服饰', '美妆', '食品'];
  const rows = [];
  for (let i = 0; i < 42; i++) {
    const qty = 1 + Math.floor(r() * 6);
    const price = Math.round((20 + r() * 980) * 100) / 100;
    const isRefund = r() < 0.12;
    let amount = Math.round(qty * price * 100) / 100;
    if (i === 7) amount = 128000;            // 大宗团购离群值
    if (i === 25) amount = 3;                // 异常低价
    const discount = r() < 0.18 ? null : Math.round(r() * 40 + 5);
    rows.push([
      `ORD${String(2026001 + i)}`,
      cities[Math.floor(r() * cities.length)],
      cats[Math.floor(r() * cats.length)],
      qty,
      price,
      amount,
      discount,
      isRefund ? '已退款' : '已完成',
    ]);
  }
  return new DataFrame(
    ['订单号', '城市', '品类', '数量', '单价', '金额', '折扣率', '状态'],
    rows,
    {
      name: 'orders',
      source: '内置数据集 · 电商订单流水',
      meta: {
        title: '电商订单流水',
        subtitle: '42 条订单 · 含极端金额与缺失折扣率',
        unit: { 金额: '元', 单价: '元', 折扣率: '%', 数量: '件' },
      },
    }
  );
}

/* ------------------------- 备用数据集 3：城市气温 ------------------------- */

function weatherFrame() {
  const r = rng(7);
  const cities = ['哈尔滨', '北京', '上海', '广州', '昆明'];
  const base = { 哈尔滨: 4, 北京: 13, 上海: 18, 广州: 24, 昆明: 17 };
  const dates = [];
  for (let m = 1; m <= 6; m++) for (let d = 1; d <= 6; d++) dates.push(`03-${String(m).padStart(2, '0')}${d}`);
  const rows = [];
  dates.forEach((dt, i) => {
    const city = cities[i % cities.length];
    const t = base[city] + (r() * 8 - 4) + Math.sin(i / 6) * 3;
    rows.push([dt, city, Math.round(t * 10) / 10, Math.round((40 + r() * 50) * 10) / 10, Math.round(r() * 12 * 10) / 10]);
  });
  return new DataFrame(['日期', '城市', '气温', '湿度', '风速'], rows, {
    name: 'weather',
    source: '内置数据集 · 城市气象观测',
    meta: {
      title: '城市气象观测',
      subtitle: '36 条观测记录 · 适合时间序列演示',
      unit: { 气温: '℃', 湿度: '%', 风速: 'm/s' },
    },
  });
}

